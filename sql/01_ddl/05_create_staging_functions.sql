CREATE OR REPLACE FUNCTION staging.try_boolean(p_value TEXT)
RETURNS BOOLEAN
LANGUAGE SQL
IMMUTABLE
AS $$
    SELECT CASE LOWER(NULLIF(BTRIM(p_value), ''))
        WHEN '1' THEN TRUE
        WHEN '0' THEN FALSE
        WHEN 'true' THEN TRUE
        WHEN 'false' THEN FALSE
        WHEN 't' THEN TRUE
        WHEN 'f' THEN FALSE
        WHEN 'yes' THEN TRUE
        WHEN 'no' THEN FALSE
        ELSE NULL
    END;
$$;
